/* ---------- utils ---------- */
function escapeHtml(s) {
  return String(s == null ? "" : s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}
function initials(name) {
  return (name || "?").split(" ").map((w) => w[0]).slice(0, 2).join("").toUpperCase();
}
function timeAgo(iso) {
  const diff = Date.now() - new Date(iso).getTime();
  const m = Math.floor(diff / 60000), h = Math.floor(m / 60), d = Math.floor(h / 24);
  if (m < 1) return "just now";
  if (m < 60) return m + "m ago";
  if (h < 24) return h + "h ago";
  if (d < 30) return d + "d ago";
  return new Date(iso).toLocaleDateString();
}
function fmtDate(iso) {
  return new Date(iso).toLocaleString(undefined, { month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" });
}
function statusBadge(status) {
  return '<span class="badge ' + (CMTS.statusClass[status] || "") + '"><span class="dot"></span>' + escapeHtml(status) + "</span>";
}
function prioBadge(p) {
  const map = { Low: 'p-low', Medium: 'p-med', High: 'p-high', Critical: 'p-crit' };
  return '<span class="prio ' + (map[p] || '') + '"><span class="dot"></span>' + escapeHtml(p) + '</span>';
}

/* ---------- toast ---------- */
function toast(title, msg, type) {
  const wrap = document.getElementById("toasts");
  const el = document.createElement("div");
  el.className = "toast " + (type || "");
  el.innerHTML = '<div>' + icon(type === "error" ? "alert" : type === "success" ? "checkCircle" : "bell") +
    '</div><div><div class="t-title">' + escapeHtml(title) + "</div>" +
    (msg ? '<div class="t-msg">' + escapeHtml(msg) + "</div>" : "") + "</div>";
  wrap.appendChild(el);
  setTimeout(() => { el.style.opacity = "0"; el.style.transform = "translateX(20px)"; setTimeout(() => el.remove(), 250); }, 3500);
}

/* ---------- modal helpers ---------- */
function openModal(html, size) {
  const ov = document.getElementById("modal-overlay");
  ov.innerHTML = '<div class="modal ' + (size || "") + '" role="dialog" aria-modal="true">' + html + "</div>";
  ov.classList.add("show");
}
function closeModal() {
  const ov = document.getElementById("modal-overlay");
  ov.classList.remove("show");
  ov.innerHTML = "";
}
function openLightbox(src) {
  const lb = document.getElementById("lightbox");
  lb.querySelector("img").src = src;
  lb.classList.add("show");
}
